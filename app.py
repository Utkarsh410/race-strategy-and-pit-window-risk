"""RaceSim Streamlit dashboard.

Launch with:  streamlit run app.py

The dashboard is a thin UI over the ``racesim`` package: every calculation is
performed by the simulation engine in ``src/racesim``.
"""

from __future__ import annotations

import logging
import sys
from pathlib import Path

import streamlit as st

ROOT = Path(__file__).resolve().parent
for p in (ROOT, ROOT / "src"):  # allow running without an editable install
    if str(p) not in sys.path:
        sys.path.insert(0, str(p))

from dashboard import (  # noqa: E402
    overview, pit_window_view, replanning_view, rival_analysis, risk_analysis, strategy_planner, telemetry_analysis,
    uncertainty_view,
)
from dashboard.common import cached_synthetic, make_context, ss  # noqa: E402
from dashboard.theme import apply_brand  # noqa: E402
from racesim.data_ingestion import DataValidationError, load_race_dataframe, read_lap_csv  # noqa: E402
from racesim.data_validation import clean_lap_times  # noqa: E402

logging.basicConfig(level=logging.WARNING, format="%(levelname)s %(name)s: %(message)s")

st.set_page_config(page_title="RaceSim - Strategy & Pit-Window Risk", page_icon=":material/sports_motorsports:", layout="wide")

apply_brand()


def load_data(ctx) -> None:
    """Load demo or uploaded lap data into the context (kept separate from results)."""
    with st.sidebar:
        st.header("Lap data")
        source = st.radio("Data source", ["Synthetic demo data", "Upload CSV"], key="data_source",
                          help="Synthetic data are generated by RaceSim's own model and are clearly labelled SYNTHETIC.")
        if source == "Synthetic demo data":
            anomalies = st.checkbox("Inject demo data anomalies", value=True, key="demo_anomalies",
                                    help="Adds one duplicate row and one missing lap time to demonstrate validation.")
            df, meta = cached_synthetic(ctx.setup_json, int(ss("mc_seed", ctx.setup.race.simulation_seed)), anomalies)
            ctx.data_label = "SYNTHETIC demo data (generated by RaceSim)"
            st.download_button("Download demo CSV", df.to_csv(index=False).encode(), "synthetic_demo_race.csv", "text/csv")
        else:
            up = st.file_uploader("Lap-level CSV or MoTeC CSV export", type=["csv"],
                                  help="Lap-level CSV: columns lap (or lap_number) and lap_time_s, in seconds or as 1:50.485; "
                                       "comma, semicolon or tab separated. A MoTeC i2 CSV export gives lap times from its beacon "
                                       "markers. See README for the schema.")
            if up is None:
                st.info("Upload a CSV to enable telemetry analysis.")
                return
            try:
                df, ctx.data_label, notes = read_lap_csv(up, up.name)
            except Exception as exc:  # malformed files are reported, not raised
                st.error(f"Could not read {up.name}: {exc}")
                return
            for note in notes:
                st.caption(note)
    try:
        ctx.data = load_race_dataframe(df, source=ctx.data_label)
    except DataValidationError as exc:
        st.sidebar.error(str(exc))
        return
    if ctx.data.report.valid:
        ctx.cleaning = clean_lap_times(ctx.data.data)


def main() -> None:
    ctx = make_context()
    st.title("RaceSim - Race Strategy and Pit-Window Risk Simulator")
    st.markdown(f"<div class='synthetic-banner'><b>{ctx.setup.race.data_label}.</b> "
                "Outputs are model predictions, not guarantees of any race result.</div>", unsafe_allow_html=True)
    if ctx.config_error:
        st.error(ctx.config_error)
    load_data(ctx)
    with st.sidebar:
        st.header("Random seed")
        st.number_input("Simulation seed", min_value=0, step=1, key="mc_seed",
                        help="Seeds the Monte Carlo engine and the synthetic demo data.")
        st.caption("Model assumptions are set inside each section and shared by every analysis.")
    tabs = st.tabs(["A. Race overview", "B. Strategy planner", "C. Pit window", "D. Monte Carlo risk",
                    "E. Rival strategy", "F. Telemetry & validation", "G. Dynamic replanning", "H. Sensitivity & uncertainty"])
    sections = [overview, strategy_planner, pit_window_view, risk_analysis, rival_analysis, telemetry_analysis, replanning_view,
                uncertainty_view]
    for tab, section in zip(tabs, sections):
        with tab:
            try:
                section.render(ctx)
            except Exception as exc:  # keep other sections usable
                logging.getLogger("racesim.dashboard").exception("Section failed")
                st.error(f"This section could not be rendered: {exc}")


main()
