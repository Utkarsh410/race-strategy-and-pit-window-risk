"""Section F - telemetry (lap data), data quality and model validation."""

from __future__ import annotations

import pandas as pd
import streamlit as st

from dashboard.common import DashboardContext, show, to_csv_bytes
from racesim.fuel_model import estimate_fuel_consumption
from racesim.lap_time_model import calculate_sector_statistics, calculate_stint_pace, detect_pace_trend, estimate_pace_uncertainty
from racesim.plotting import (
    plot_lap_time_progression,
    plot_model_residuals,
    plot_residuals_by_age,
    plot_sector_comparison,
    plot_stint_pace,
    plot_tyre_degradation,
)
from racesim.tyre_model import compare_tyre_compounds, estimate_tyre_degradation
from racesim.validation import generate_validation_report


@st.cache_data(show_spinner="Validating the tyre model on held-out stints...", max_entries=8)
def _validation(df: pd.DataFrame, fuel_effect: float, method: str, seed: int) -> dict:
    return generate_validation_report(df, fuel_effect_s_per_kg=fuel_effect, method=method, seed=seed)


def render(ctx: DashboardContext) -> None:
    if ctx.data is None:
        st.info("No lap data loaded. Choose the synthetic demo data or upload a CSV in the sidebar.")
        return
    rep = ctx.data.report
    st.caption(f"Data source: **{ctx.data_label}**. Uploaded/observed data are kept separate from simulated results.")
    if "data_source" in ctx.data.data.columns and ctx.data.data["data_source"].astype(str).str.contains("SYNTHETIC").any():
        st.warning("These laps are SYNTHETIC - generated by RaceSim's own model, not real telemetry.")
    st.subheader("Data-quality report")
    k = st.columns(5)
    k[0].metric("Rows", rep.n_rows)
    k[1].metric("Invalid lap times", rep.invalid_lap_time_count)
    k[2].metric("Duplicate rows", rep.duplicate_lap_count)
    k[3].metric("Flagged outliers", rep.outlier_count, help="Flagged for inspection, not deleted.")
    k[4].metric("Optional columns present", f"{len(rep.available_optional_columns)}")
    for e in rep.errors:
        st.error(e)
    for w in rep.warnings:
        st.warning(w)
    if not rep.valid or ctx.cleaning is None:
        st.error("Dataset cannot be analysed until the errors above are fixed.")
        return
    ann = ctx.cleaning.annotated
    with st.expander("Flagged records (inspect before trusting the fits)"):
        flagged = ann[ann["flag_invalid"] | ann["flag_duplicate"] | ann["flag_outlier"]]
        st.dataframe(flagged, hide_index=True)
        st.json(ctx.cleaning.summary)
    st.download_button("Download annotated (cleaned + flags) CSV", to_csv_bytes(ann), "annotated_laps.csv", "text/csv")

    cols = set(ann.columns)
    setup = ctx.setup
    st.subheader("Lap-time progression")
    show(plot_lap_time_progression(ann[~ann["flag_invalid"]], title="Observed lap times (shaded: SC/VSC laps)"))
    st.subheader("Sector comparison")
    sectors = calculate_sector_statistics(ann)
    if sectors.empty:
        st.info("Sector analysis disabled: columns sector1_s, sector2_s, sector3_s are not present.")
    else:
        show(plot_sector_comparison(sectors))
    st.subheader("Stint pace and tyre degradation")
    if not {"tyre_compound", "tyre_age_laps"} <= cols:
        st.info("Tyre analysis disabled: columns tyre_compound and tyre_age_laps are required.")
    else:
        stints = calculate_stint_pace(ann, fuel_effect_s_per_kg=setup.race.fuel_effect_s_per_kg)
        show(plot_stint_pace(stints))
        fuel_note = "using the fuel_kg column" if "fuel_kg" in cols else "using the configured fuel ASSUMPTION"
        est = estimate_tyre_degradation(ann, fuel_effect_s_per_kg=setup.race.fuel_effect_s_per_kg,
                                        fuel_consumption_kg_per_lap=setup.race.fuel_consumption_kg_per_lap)
        rows = [{"compound": e.compound, "estimated_linear_s_per_lap": e.linear_degradation_s_per_lap,
                 "std_error_s_per_lap": e.standard_error_s_per_lap, "laps": e.sample_count, "stints": e.stint_count,
                 "reliable": e.reliable, "configured_linear_s_per_lap": setup.compounds[e.compound].linear_degradation_s_per_lap
                 if e.compound in setup.compounds else None, "warnings": " | ".join(e.warnings)} for e in est.values()]
        st.caption(f"Within-stint fit on representative laps, fuel-corrected {fuel_note}; warm-up laps after stops excluded.")
        st.dataframe(pd.DataFrame(rows), hide_index=True)
        curves = compare_tyre_compounds({c: m for c, m in setup.compounds.items() if c in ann["tyre_compound"].astype(str).unique()},
                                        max_age_laps=int(ann["tyre_age_laps"].max() or 1),
                                        reference_temperature_c=setup.race.reference_track_temperature_c,
                                        track_temperature_c=setup.race.track_temperature_c)
        show(plot_tyre_degradation(curves, observed=ann, fuel_effect_s_per_kg=setup.race.fuel_effect_s_per_kg,
                                   title="Observed degradation (markers) vs configured model (lines)"))
    c1, c2 = st.columns(2)
    with c1:
        st.markdown("**Pace trend**")
        st.dataframe(detect_pace_trend(ann), hide_index=True)
    with c2:
        st.markdown("**Lap-to-lap variability & fuel**")
        pu = estimate_pace_uncertainty(ann)
        fe = estimate_fuel_consumption(ann, assumed_kg_per_lap=setup.race.fuel_consumption_kg_per_lap)
        st.write({"residual lap std (s)": pu["lap_time_std_s"], "robust std (s)": pu["robust_std_s"], "laps": pu["sample_count"],
                  "fuel consumption (kg/lap)": fe.kg_per_lap, "fuel source": fe.source})
        for w in fe.warnings + ([pu["warning"]] if pu.get("warning") else []):
            st.caption(w)

    st.subheader("Model validation (held-out stints)")
    if not {"tyre_compound", "tyre_age_laps"} <= cols:
        st.info("Validation disabled: tyre columns are required.")
        return
    c = st.columns(2)
    method = c[0].selectbox("Split", ["stint", "driver"], help="Whole stints (or drivers) are held out to avoid leakage between adjacent laps.")
    seed = c[1].number_input("Split seed", 0, 1000, value=0)
    vr = _validation(ann, setup.race.fuel_effect_s_per_kg, method, int(seed))
    for w in vr["warnings"]:
        st.warning(w)
    if vr["status"] != "conclusive":
        st.info("Validation inconclusive - no accuracy figures are reported.")
        return
    mt = pd.DataFrame([{"model": m, "MAE (s)": v["mae_s"], "RMSE (s)": v["rmse_s"], "bias (s, pred - obs)": v["bias_s"],
                        "validation laps": v["n_validation"], "training laps": v["n_train"]} for m, v in vr["models"].items()])
    st.dataframe(mt, hide_index=True)
    if "comparison" in vr:
        st.caption(vr["comparison"])
    c1, c2 = st.columns(2)
    with c1:
        show(plot_model_residuals(vr["predictions"]))
    with c2:
        show(plot_residuals_by_age(vr["predictions"]))
